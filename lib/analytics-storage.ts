let ensured: Promise<void> | null = null

/** Make sure every analytics table, column and index exists. Runs once per process. */
export function ensureAnalyticsStorage(): Promise<void> {
  if (!ensured) {
    ensured = (async () => {
      for (const statement of STATEMENTS) await pool.query(statement)
    })().catch((err) => {
      console.error("[analytics] storage setup failed:", (err as Error)?.message)
      ensured = null
      throw err
    })
  }
  return ensured
}
